            NetworkSortOption.SSID_ASC -> "الاسم أبجدياً"
        }
    } else option.label

    fun securityFilterLabel(filter: SecurityFilter): String = if (isArabic) {
        when (filter) {
            SecurityFilter.ALL -> "الكل"
            SecurityFilter.WEAK_OR_OPEN -> "ضعيفة / مفتوحة"
            SecurityFilter.WPA2 -> "WPA2"
            SecurityFilter.WPA3 -> "WPA3"
        }
    } else filter.label

    fun signalQualityLabel(rssiDbm: Int): String = if (isArabic) {
        when {
            rssiDbm >= -55 -> "ممتازة"
            rssiDbm >= -67 -> "جيدة"
            rssiDbm >= -75 -> "متوسطة"
            rssiDbm >= -85 -> "ضعيفة"
            else -> "حرجة"
        }
    } else {
        when {
            rssiDbm >= -55 -> "EXCELLENT"
            rssiDbm >= -67 -> "GOOD"
            rssiDbm >= -75 -> "FAIR"
            rssiDbm >= -85 -> "WEAK"
            else -> "CRITICAL"
        }
    }
}

