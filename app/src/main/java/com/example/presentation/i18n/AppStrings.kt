    fun riskLabel(level: RiskLevel): String = if (isArabic) {
        when (level) {
            RiskLevel.SECURE -> "آمن"
            RiskLevel.LOW -> "خطر منخفض"
            RiskLevel.MODERATE -> "متوسط"
            RiskLevel.HIGH -> "خطر مرتفع"
            RiskLevel.CRITICAL -> "حرج"
        }
    } else level.label

    fun auditStatusLabel(status: AuditCheckStatus): String = if (isArabic) {
        when (status) {
            AuditCheckStatus.PASS -> "ناجح"
            AuditCheckStatus.WARN -> "تنبيه"
            AuditCheckStatus.FAIL -> "فشل"
            AuditCheckStatus.INFO -> "معلومة"
